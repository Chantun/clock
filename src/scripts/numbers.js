function ascciParser(char) {
	switch (char) {
		case '-':
			return [180, 0];
		case '|':
			return [270, 90];
		case '┐':
			return [180, 90];
		case '┌':
			return [0, 90];
		case '└':
			return [270, 0];
		case '┘':
			return [180, 270];
		default:
			return [135, 135];
	}
}
